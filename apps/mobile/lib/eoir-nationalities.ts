/**
 * EOIR's own nationality list, fetched verbatim on 2026-09-17 from the
 * Gatsby static query that ACIS's nationality dropdown itself is built
 * from (acis.eoir.justice.gov/page-data/sq/d/1791802679.json), filtered
 * the same way their own code filters it (they drop code "??",
 * "UNKNOWN NATIONALITY").
 *
 * The codes are EOIR's OWN, NOT ISO 3166 — ARUBA is "AB", ALGERIA "AG",
 * AUSTRALIA "AS", CHINA "CH". Guessing them from ISO would be wrong for a
 * large fraction of the list, which is exactly why this is transcribed
 * from their data rather than generated.
 *
 * ACIS renders each option as `NAME + " (" + CODE + ")"`, so
 * eoirNationalityLabel() below reproduces their label exactly and autofill
 * can match an option by full string equality. That matters: an earlier
 * version matched on "does the option text contain the country name",
 * which picked BRITISH INDIAN OCEAN TERRITORY for INDIA (it contains
 * "INDIA", and sorts first alphabetically).
 */
