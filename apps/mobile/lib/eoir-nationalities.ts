/** Exactly how ACIS labels an option in its nationality dropdown. */
export function eoirNationalityLabel(n: EoirNationality): string {
  return `${n.name} (${n.code})`;
}

export function findEoirNationality(code: string): EoirNationality | null {
  return EOIR_NATIONALITIES.find((n) => n.code === code) ?? null;
}
